-- Technik's replicated SAP and Teamcenter data: the 13 tables of TECHNIK_DW.OPS.
-- Run as SYSADMIN. Re-running replaces every table, so the data always matches seed/data.

CREATE DATABASE IF NOT EXISTS TECHNIK_DW;
CREATE SCHEMA IF NOT EXISTS TECHNIK_DW.OPS;
USE SCHEMA TECHNIK_DW.OPS;

CREATE OR REPLACE TABLE SAP_PROJECTS (
    PROJECT_ID VARCHAR, PROJECT_NAME VARCHAR, CLIENT_NAME VARCHAR, FIELD_NAME VARCHAR,
    FAT_DUE_DATE DATE, STATUS VARCHAR);

CREATE OR REPLACE TABLE SAP_UNITS (
    SERIAL_NO VARCHAR, PRODUCT_TYPE VARCHAR, MODEL VARCHAR, PROJECT_ID VARCHAR,
    PLANT VARCHAR, STATUS VARCHAR);

CREATE OR REPLACE TABLE SAP_BOM_LINES (
    PARENT_PART_NO VARCHAR, COMPONENT_PART_NO VARCHAR, QTY NUMBER(10, 0));

CREATE OR REPLACE TABLE SAP_WORK_ORDERS (
    WO_NO VARCHAR, PART_NO VARCHAR, SERIAL_NO VARCHAR, PROJECT_ID VARCHAR, PLANT VARCHAR,
    RELEASED_AT TIMESTAMP_NTZ, COMPLETED_AT TIMESTAMP_NTZ, STATUS VARCHAR);

-- One row per confirmation, not per operation. Where an operation has two, the higher
-- CONFIRMATION_NO is the posting that counts.
CREATE OR REPLACE TABLE SAP_WO_OPERATIONS (
    WO_NO VARCHAR, OP_SEQ VARCHAR, OPERATION VARCHAR, WORK_CENTER VARCHAR,
    ROUTING_HOURS NUMBER(6, 1), ACTUAL_HOURS NUMBER(6, 1),
    PLANNED_START TIMESTAMP_NTZ, ACTUAL_START TIMESTAMP_NTZ, ACTUAL_END TIMESTAMP_NTZ, STATUS VARCHAR,
    DRAWING_NO VARCHAR, DRAWING_REV VARCHAR, CNC_PROGRAM_NO VARCHAR, CNC_PROGRAM_REV VARCHAR,
    WORK_INSTRUCTION_NO VARCHAR, CONFIRMATION_NO VARCHAR, CONFIRMED_AT TIMESTAMP_NTZ);

CREATE OR REPLACE TABLE SAP_QUALITY_NOTIFICATIONS (
    QN_NO VARCHAR, WO_NO VARCHAR, SERIAL_NO VARCHAR, PART_NO VARCHAR, OPERATION VARCHAR,
    DEFECT_TYPE VARCHAR, DESCRIPTION VARCHAR, PRIORITY VARCHAR, STATUS VARCHAR,
    CREATED_AT TIMESTAMP_NTZ, CLOSED_AT TIMESTAMP_NTZ);

CREATE OR REPLACE TABLE TC_PARTS (
    PART_NO VARCHAR, REVISION VARCHAR, DESCRIPTION VARCHAR, RELEASE_STATUS VARCHAR,
    RELEASED_AT TIMESTAMP_NTZ);

CREATE OR REPLACE TABLE TC_DRAWINGS (
    DRAWING_NO VARCHAR, REVISION VARCHAR, PART_NO VARCHAR, TITLE VARCHAR, RELEASE_STATUS VARCHAR,
    RELEASED_AT TIMESTAMP_NTZ);

CREATE OR REPLACE TABLE TC_DOCUMENTS (
    DOC_NO VARCHAR, DOC_TYPE VARCHAR, REVISION VARCHAR, TITLE VARCHAR, OWNER VARCHAR,
    STATUS VARCHAR, RELEASED_AT TIMESTAMP_NTZ, NEXT_REVIEW_DATE DATE);

CREATE OR REPLACE TABLE TC_CNC_PROGRAMS (
    PROGRAM_NO VARCHAR, REVISION VARCHAR, PART_NO VARCHAR, MACHINE VARCHAR, RELEASE_STATUS VARCHAR,
    RELEASED_AT TIMESTAMP_NTZ);

CREATE OR REPLACE TABLE TC_ECNS (
    ECN_NO VARCHAR, TITLE VARCHAR, REASON VARCHAR, STATUS VARCHAR,
    CREATED_AT TIMESTAMP_NTZ, RELEASED_AT TIMESTAMP_NTZ);

CREATE OR REPLACE TABLE TC_ECN_AFFECTED_ITEMS (
    ECN_NO VARCHAR, ITEM_NO VARCHAR, ITEM_TYPE VARCHAR, FROM_REV VARCHAR, TO_REV VARCHAR);

CREATE OR REPLACE TABLE FAT_RESULTS (
    SERIAL_NO VARCHAR, TEST_ID VARCHAR, TEST_NAME VARCHAR, RESULT VARCHAR,
    TESTED_AT TIMESTAMP_NTZ, RAW VARIANT);
